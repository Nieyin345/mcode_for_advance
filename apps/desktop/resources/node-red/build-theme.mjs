#!/usr/bin/env node
/**
 * T47: build the two official Node-RED 5.0.8 SCSS variable themes and a single
 * media-query entrypoint for the Electron host. No vendor sources are changed.
 *
 * Run from any cwd:
 *   node apps/desktop/resources/node-red/build-theme.mjs
 */
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const dir = dirname(fileURLToPath(import.meta.url));
const root = resolve(dir, "../../../..");
const builder = join(root, "node-red", "scripts", "build-custom-theme.js");
const themes = {};
for (const mode of ["light", "dark"]) {
  const input = join(dir, `mcode-colors-${mode}.scss`);
  const output = join(dir, `mcode-theme-${mode}.css`);
  execFileSync(process.execPath, [builder, "--in", input, "--out", output], {
    cwd: root, stdio: "inherit",
  });
  // Node-RED's builder puts the current timestamp in the CSS header.
  // Strip only the timestamp comment: the actual compiled CSS stays intact.
  const raw = readFileSync(output, "utf8");
  const css = raw.replace(/^\/\*\s*\* Theme generated with Node-RED .*?\*\/\s*/s, "").trim();
  if (css === raw.trim() || !css.includes("--red-ui-primary-background")) {
    throw new Error(`Unexpected official Node-RED CSS output: ${output}`);
  }
  writeFileSync(output,
    `/* Generated by Node-RED 5.0.8 build-custom-theme.js from mcode-colors-${mode}.scss. */\n${css}\n`);
  themes[mode] = css;
}

// Radius-only rules: Node-RED native canvas geometry, palette node semantic
// colours and the workspace grid remain untouched. Native CSS variables power
// all the colour mappings in both modes.
const chrome = (
  ".red-ui-button,.red-ui-header-button,.red-ui-menu-item,"
  + ".red-ui-palette-node,.red-ui-tab,.red-ui-workspace-button{border-radius:6px;}"
  + ".red-ui-dialog,.red-ui-popover,.red-ui-menu,.red-ui-sidebar{border-radius:8px;}"
);
writeFileSync(join(dir, "mcode-theme-auto.css"),
  "/* Mcode T47. A single static URL: Electron nativeTheme drives prefers-color-scheme. */\n"
  + ":root{color-scheme:light;}\n"
  + themes.light + "\n" + chrome + "\n"
  + "@media (prefers-color-scheme: dark){:root{color-scheme:dark;}"
  + themes.dark + "}\n");
