/* T42: deterministic esbuild CJS payload embedded in main's generated TS.
 * One standalone bundle for all six Node-RED types, built BEFORE electron-vite.
 * No live ts-node/NODE_PATH resolution in the shipped child process.
 */
const fs = require("node:fs");
const path = require("node:path");
const root = path.resolve(__dirname, "../../..");
const packages = path.join(root, "node_modules/.pnpm");
const candidates = fs.readdirSync(packages).filter((s) => /^esbuild@/.test(s)).sort();
if (!candidates.length) throw Error("esbuild is required to build the Mcode Node-RED node pack");
const esbuild = require(path.join(packages, candidates[candidates.length - 1], "node_modules/esbuild"));
const compiled = esbuild.buildSync({
  entryPoints: [path.join(__dirname, "../src/main/workflowEngines/nodePackChildRuntime.ts")],
  platform: "node", format: "cjs", target: "node20", bundle: true, write: false,
  tsconfig: path.join(__dirname, "../tsconfig.json"), logLevel: "error",
});
const code = compiled.outputFiles[0].text;
if (!code.includes("mcode-node-request")) throw Error("Node pack bundle lost IPC transport");
const dest = path.join(__dirname, "../src/main/workflowEngines/nodePackBundle.generated.ts");
const text = "// Generated by apps/desktop/build/build-node-pack.cjs. Do not edit by hand.\n"
  + "export const MCODE_NODE_PACK_BUNDLE = " + JSON.stringify(code) + ";\n";
if (!fs.existsSync(dest) || fs.readFileSync(dest, "utf8") !== text)
  fs.writeFileSync(dest, text, "utf8");
console.log("Mcode Node-RED CJS bundle bytes=" + Buffer.byteLength(code));
