/**
 * 设置页正文的宽度。**只有两档,没有第三档。**
 *
 * ## 为什么要有这个文件
 *
 * 之前每个面板各写各的:大多数是 `max-w-3xl`(768px),技能和模型配置是 `max-w-5xl`,
 * 工作流和钩子是 `max-w-6xl`。切换设置页时正文的宽度会跳一下 —— 而**没有任何一处**
 * 是故意选那个值的,它们只是各写各的。
 *
 * 所以宽度收成两个名字。加新页面时挑一档,不要写字面量。
 *
 * ## `canvas` 这一档为什么存在(试过合并,不行)
 *
 * 2026-09-15 试过一次把两档并成一档(全用 `form`),结果**工作流那一页太小了** ——
 * 用户当场看出来了。原因是可以算的:
 *
 *   正文 768px − 库列表 200px − 两个间隔 ≈ 24px = **544px** 给画布和检查器;
 *   而检查器那一栏 300px、节点宽 208px、列间距 72px(见 `workflowLayout.ts`)——
 *   并排两个节点就要 488px。544 减掉检查器只剩 244px,**连一个节点都放不下**。
 *
 * 当时为了塞进去还把检查器挪到了画布下方,那样确实放下了,但画布只剩一半高度、整页
 * 也变窄了 —— 结论是这一页**本来就该宽**,不是"没对齐"。
 *
 * 所以这条线不是审美问题:**正文里有没有一张可以拖的图**。有,就得给够。
 * 真要把它并到 `form`,先得改画布那一块自己的排布(比如让检查器变成抽屉),那是另一件事。
 */
export const PANEL_MAX_W = {
  /** 表单 / 列表页。与「MCP」那一页同宽 —— 它就是这一档的参照。 */
  form: "max-w-3xl",
  /** 正文里有画布的页(工作流 / 自动化)。理由见文件头。 */
  canvas: "max-w-6xl",
} as const;
