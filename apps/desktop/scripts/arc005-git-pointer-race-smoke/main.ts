import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { GitScanGeneration } from "../../src/renderer/components/ide/gitScanGeneration.js";
import { shouldFinishDividerDrag } from "../../src/renderer/components/layout/dividerDragIdentity.js";
let ok=0, failed=0;
const check=(name:string,cond:boolean)=>{console.log(`${cond?"PASS":"FAIL"} ${name}`); if(cond)ok++;else failed++;};
const src=(p:string)=>readFileSync(resolve("src/renderer/components",p),"utf8");
const git=src("ide/GitPanel.tsx");
const divider=src("layout/Divider.tsx");
check("Git scan generation invalidates on project clear",git.includes("scanGeneration.current.invalidate()") && git.includes("if (!projectPath)"));
check("Git scan generation cancels outstanding work on unmount",git.includes("return () => scanGeneration.current.invalidate()"));
check("Git scan writes only for latest generation",git.includes("scanGeneration.current.isCurrent(seq)"));
check("Git sub-tabs expose semantic selected state",git.includes("aria-pressed={active}"));
check("Git icon-only rescan has accessible name",git.includes('aria-label={t("ide.git.rescanRepos")}'));
check("Divider finish on pointer up checks pointer identity",divider.includes("finishPointer(e.pointerId)") && divider.includes("onPointerCancel={(e) => finishPointer(e.pointerId)}"));
check("Divider ignores foreign pointer capture loss",divider.includes("onLostPointerCapture={(e) => finishPointer(e.pointerId)}"));
check("Divider retains window blur and unmount forced cleanup",divider.includes('window.addEventListener("blur", finish)') && divider.includes("return () => { finish();"));
const generation = new GitScanGeneration();
const scanA = generation.next();
check("first Git scan is current",generation.isCurrent(scanA));
generation.invalidate();
check("project removed invalidates in-flight scan",!generation.isCurrent(scanA));
const scanB = generation.next();
const scanC = generation.next();
check("newest Git refresh supersedes prior request",!generation.isCurrent(scanB) && generation.isCurrent(scanC));
check("invalid scan tokens fail closed",!generation.isCurrent(0) && !generation.isCurrent(-1) && !generation.isCurrent(NaN));
generation.invalidate();
check("unmount blocks even the most recent response",!generation.isCurrent(scanC));

check("active pointer release ends its drag",shouldFinishDividerDrag(5,5));
check("secondary pointer release cannot cancel active drag",!shouldFinishDividerDrag(5,6));
check("no active pointer is always ignored",!shouldFinishDividerDrag(null,5));
check("pointer zero remains a valid primary pointer",shouldFinishDividerDrag(0,0));
console.log(`arc005-git-pointer-race ${ok}/${ok+failed}`);
if(failed) process.exitCode=1;
