/**
 * ARC-007: REAL disk regressions for PDF backup, sidecar temp collisions,
 * and invalid writeback. Only synthetic files under mkdtempSync(tmpdir()).
 */
import { mkdtempSync, existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { createRequire, syncBuiltinESMExports } from "node:module";
import {
  originalPathFor, highlightsPathFor, ensureOriginal, hasOriginal,
  readHighlights, writeHighlights, writeBackToFile,
} from "@main/library/pdfHighlightsStore.js";

let checks=0,failures=0;
function check(name:string,yes:boolean,more?:unknown){
 checks++;if(yes) console.log("  ok   "+name);
 else {failures++;console.log("  FAIL "+name+" "+JSON.stringify(more));}
}
const root=mkdtempSync(join(tmpdir(),"mcode-pdf-integrity-"));
const pdf=join(root,"paper.pdf");
const original=originalPathFor(pdf);
const sidecar=highlightsPathFor(pdf);
try {
  writeFileSync(pdf,"%PDF-1.7 unannotated original");
  ensureOriginal(pdf,new TextEncoder().encode("%PDF-1.7 clean first"));
  check("normal first ensureOriginal makes clean baseline",hasOriginal(pdf)&&readFileSync(original,"utf8")==="%PDF-1.7 clean first");
  ensureOriginal(pdf,new TextEncoder().encode("%PDF-1.7 later modified"));
  check("normal second ensureOriginal never overwrites first baseline",readFileSync(original,"utf8")==="%PDF-1.7 clean first");

  // Race injection at the EXISTENCE-CHECK boundary: two processes both
  // observe absent, then another process creates the immutable baseline.
  // Forcing one stale check reproduces that state deterministically.
  const req=createRequire(import.meta.url);
  const fs=req("node:fs") as {existsSync:(p:unknown)=>boolean};
  const realExists=fs.existsSync;
  try{
    fs.existsSync=(p:unknown)=>String(p)===original ? false : realExists(p);
    syncBuiltinESMExports();
    let thrown="";
    try{ensureOriginal(pdf,new TextEncoder().encode("%PDF-1.7 racing loser"));}
    catch(e){thrown=String(e);}
    check("★★ stale existence check cannot overwrite first owner's original PDF",readFileSync(original,"utf8")==="%PDF-1.7 clean first",{thrown,current:readFileSync(original,"utf8")});
  }finally{
    fs.existsSync=realExists;
    syncBuiltinESMExports();
  }
  check("original backup temporary files are cleaned after race",
    !readdirSync(root).some(name=>name.startsWith(".paper.pdf.mcode-original.pdf.") && name.endsWith(".tmp")),
    readdirSync(root));

  writeHighlights(pdf,[]);
  check("normal empty sidecar stays a valid versioned record",Array.isArray(readHighlights(pdf)));
  // A stale abandoned temp file from a different writer must not be stolen
  // just because another write happened in the same millisecond.
  const realNow=Date.now;
  const fakeNow=1234567890;
  const collided=sidecar+"."+fakeNow.toString(36)+".tmp";
  writeFileSync(collided,"OTHER WRITER OWNED THIS TEMP BYTES");
  try{
    Date.now=()=>fakeNow;
    writeHighlights(pdf,[]);
  }finally{
    Date.now=realNow;
  }
  check("★★ a preexisting same-ms temporary file is never overwritten",
    existsSync(collided) && readFileSync(collided,"utf8")==="OTHER WRITER OWNED THIS TEMP BYTES");
  check("normal sidecar rewrite still succeeds",readHighlights(pdf).length===0);
  rmSync(collided,{force:true});

  const originalPdf=readFileSync(pdf,"utf8");
  // This fixture has a genuine xref, trailer, page tree and %%EOF; unlike
  // the old fake "%PDF-1.7 valid output" positive, pdf.js can reopen it.
  const validBytes=new Uint8Array(readFileSync(join(process.cwd(),"scripts","fixtures","sample-paper.pdf")));
  const realBackup=readFileSync(original);
  for(const [name,badBytes] of [
    ["empty saveDocument result",new Uint8Array()],
    ["non-PDF output",new TextEncoder().encode("not a PDF but bytes")],
    ["five-byte header only",new TextEncoder().encode("%PDF-")],
    ["header and fake EOF without objects",new TextEncoder().encode("%PDF-1.7\\n%%EOF\\n")],
    ["truncated real PDF without EOF",validBytes.subarray(0,validBytes.length-24)],
    ["fake PDF magic amid unrelated bytes",new TextEncoder().encode("not pdf %PDF-1.7\\n%%EOF\\n")],
  ] as const) {
    let errored=false;
    try{await writeBackToFile(pdf,[],async()=>badBytes);}
    catch {errored=true;}
    check("★★ "+name+": writeback refuses invalid generated bytes",errored);
    check("★★ "+name+": source PDF byte-for-byte unchanged",readFileSync(pdf,"utf8")===originalPdf);
    check("★★ "+name+": immutable original backup preserved",readFileSync(original).equals(realBackup));
    check("★★ "+name+": no abandoned writeback tmp",!readdirSync(root).some(x=>x.endsWith(".tmp.pdf")));
  }
  // Auditor E1 #1: the previous timestamp/Math.random temporary path can
  // belong to another writer. Our write must neither overwrite nor unlink it.
  const savedNow=Date.now;
  const savedRandom=Math.random;
  const fixedTime=424242424242;
  const fixedRandom=0.123456789;
  const collidedPdfTmp=join(root,
    "."+fixedTime.toString(36)+"-"+fixedRandom.toString(36).slice(2,8)+".tmp.pdf");
  const unrelatedTemp=Buffer.from("OTHER WRITER OWNS THIS TEMP FILE");
  writeFileSync(collidedPdfTmp,unrelatedTemp);
  let tmpWriteError="";
  try {
    Date.now=()=>fixedTime;
    Math.random=()=>fixedRandom;
    try{await writeBackToFile(pdf,[],async()=>validBytes.slice());}
    catch(err){tmpWriteError=String(err);}
  }finally{
    Date.now=savedNow;
    Math.random=savedRandom;
  }
  check("★★ unrelated writer's same-named temp remains intact",
    existsSync(collidedPdfTmp) && readFileSync(collidedPdfTmp).equals(unrelatedTemp),
    {exists:existsSync(collidedPdfTmp),tmpWriteError});
  rmSync(collidedPdfTmp,{force:true});

  // Auditor E1 #2: while awaiting saveDocument(), another process edits the
  // source PDF. Our old PDF snapshot must not replace its newer bytes.
  writeFileSync(pdf,validBytes);
  const concurrentBytes=Buffer.concat([Buffer.from(validBytes),Buffer.from("\n% NEW WRITER CONTENT\n")]);
  let conflictError="";
  try {
    await writeBackToFile(pdf,[],async()=>{
      writeFileSync(pdf,concurrentBytes);
      return validBytes.slice();
    });
  }catch(err){conflictError=String(err);}
  check("★★ concurrent modification is explicitly refused",
    /冲突|改动|版本|重新/.test(conflictError),conflictError);
  check("★★ concurrent writer's updated PDF survives unmodified",
    readFileSync(pdf).equals(concurrentBytes));
  check("★★ concurrent failure left no PDF temp",
    !readdirSync(root).some(x=>x.endsWith(".tmp.pdf")||x.endsWith(".mcode-tmp")));

  // Two independent Mcode callers should share the Host's per-path OS
  // lease, rather than each running saveDocument against the same revision.
  let signalFirst!:()=>void;
  let releaseFirst!:()=>void;
  const firstEntered=new Promise<void>(resolve=>{signalFirst=resolve;});
  const firstHold=new Promise<void>(resolve=>{releaseFirst=resolve;});
  const firstWrite=writeBackToFile(pdf,[],async()=>{
    signalFirst();
    await firstHold;
    return validBytes.slice();
  });
  await firstEntered;
  let secondEntered=false;
  const secondWrite=writeBackToFile(pdf,[],async()=>{
    secondEntered=true;
    return validBytes.slice();
  });
  await Promise.resolve();
  await Promise.resolve();
  check("★★ second Mcode writer cannot enter PDF save while first owns Host lease",
    !secondEntered);
  releaseFirst();
  await firstWrite;
  await secondWrite;
  check("second Mcode writer proceeds after first releases lease",secondEntered);
  check("Host file lease does not leave lock files after success",
    !readdirSync(root).some(x=>x.endsWith(".mcode-lock")));

  // The shared Host CAS and atomic file routine must continue to allow normal
  // saves and preserve the established clean-original path.
  const valid=await writeBackToFile(pdf,[],async()=>validBytes.slice());
  check("normal real PDF writeback still succeeds",
    valid.written===0&&readFileSync(pdf).equals(Buffer.from(validBytes)),valid);
  check("PDF writeback left no leftover temps",!readdirSync(root).some(name=>name.endsWith(".tmp.pdf")));
}finally{
 rmSync(root,{recursive:true,force:true});
}
console.log("pdf-highlights-integrity-smoke:"+(checks-failures)+"/"+checks+" PASS");
if(failures)process.exitCode=1;
